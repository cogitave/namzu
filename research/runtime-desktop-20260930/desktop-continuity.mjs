async function armHold(method, sessionId, captureAfter = false) {
  await desktop.evaluate(({ ipcMain }, args) => {
    // A test-only deferred boundary around the real, origin-checked IPC handler.
    // No outcome depends on a timer or how quickly the machine finishes a request.
    const original = ipcMain._invokeHandlers.get(`namzu:${args.method}`)
    const control = { original, sessionId: args.sessionId, admitted: false, release: null, done: null, ready: null, onReady: null }
    control.ready = new Promise((resolve) => { control.onReady = resolve })
    globalThis.__continuityHold = control
    ipcMain.removeHandler(`namzu:${args.method}`)
    ipcMain.handle(`namzu:${args.method}`, async (event, ...values) => {
      const target = args.method === 'providers' || args.method === 'openConversation' ? values[1] : values[0]
      if (target === control.sessionId && !control.admitted) {
        control.admitted = true
        const captured = args.captureAfter ? structuredClone(await original(event, ...values)) : null
        control.onReady()
        await new Promise((resolve) => { control.release = resolve })
        try { return args.captureAfter ? captured : await original(event, ...values) } finally { control.done?.() }
      }
      return original(event, ...values)
    })
  }, { method, sessionId, captureAfter })
}
async function releaseHold(method) {
  await desktop.evaluate(async ({ ipcMain }, method) => {
    const control = globalThis.__continuityHold
    if (!control?.admitted || !control.release) throw new Error('The held request never arrived.')
    await new Promise((resolve) => { control.done = resolve; control.release() })
    ipcMain.removeHandler(`namzu:${method}`)
    ipcMain.handle(`namzu:${method}`, control.original)
    delete globalThis.__continuityHold
  }, method)
}
