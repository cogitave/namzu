// Writes src/renderer/display-face-coverage.ts: the code points the display face's file can draw,
// read from the file's own character map, as inclusive ranges. Run it after the font file changes:
//   node scripts/generate-display-coverage.mjs
// Then format it (`npx biome format --write src/renderer/display-face-coverage.ts`). The test in
// `scripts/__tests__/display-coverage.test.mjs` reads the ranges back out of the font file and fails
// when the module on disk holds different ones, so the ranges cannot go stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { coveredCodePoints, toRanges } from './woff2-cmap.mjs'

export const FONT_FILE = fileURLToPath(
	new URL('../public/fonts/GeistPixel-Square.woff2', import.meta.url),
)
export const MODULE_FILE = fileURLToPath(
	new URL('../src/renderer/display-face-coverage.ts', import.meta.url),
)

/** The text of the module for a font file's bytes. */
export function renderCoverageModule(fontBytes) {
	const ranges = toRanges(coveredCodePoints(fontBytes))
	const body = ranges.map(([first, last]) => `\t${first}, ${last},`).join('\n')
	return `// Generated by scripts/generate-display-coverage.mjs from public/fonts/GeistPixel-Square.woff2. Do not edit.
// The code points the display face can draw, as inclusive pairs: first, last, first, last, ...
export const DISPLAY_FACE_RANGES: readonly number[] = [
${body}
]
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	writeFileSync(MODULE_FILE, renderCoverageModule(readFileSync(FONT_FILE)))
	console.log(`wrote ${MODULE_FILE}`)
}
