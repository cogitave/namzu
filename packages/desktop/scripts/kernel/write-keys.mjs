// The app's compiled key list is generated from packages/desktop/kernel-keys.json (specification 7.8),
// the one file the publisher's verify step and the release workflow read too.
//
//   node scripts/kernel/write-keys.mjs           write src/main/kernel/keys-compiled.ts
//   node scripts/kernel/write-keys.mjs --check   fail when that file is not what the list gives
//
// `pnpm build` runs the write first; a unit test runs the same comparison, so the list the app
// trusts and the file cannot differ.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { isMain, runMain } from './cli.mjs'
import { DEFAULT_KEYS_FILE, parseKeyList } from './signing.mjs'

export const COMPILED_KEYS_FILE = join(
	dirname(fileURLToPath(import.meta.url)),
	'..',
	'..',
	'src',
	'main',
	'kernel',
	'keys-compiled.ts',
)

const HEADER = [
	'// Generated by scripts/kernel/write-keys.mjs from packages/desktop/kernel-keys.json. Do not edit:',
	'// change the JSON file and run `node scripts/kernel/write-keys.mjs`.',
	'',
	'export const COMPILED_KERNEL_KEYS: readonly { id: string; publicKey: string }[] = ',
].join('\n')

/** The source text of the compiled list for the text of kernel-keys.json. Throws SigningError on a bad list. */
export function renderCompiledKeys(listText) {
	const keys = parseKeyList(listText, 'kernel-keys.json').map(({ id, publicKey }) => ({
		id,
		publicKey,
	}))
	if (keys.length === 0) return `${HEADER}[]\n`
	const entries = keys.map(
		(key) => `\t{\n\t\tid: '${key.id}',\n\t\tpublicKey: '${key.publicKey}',\n\t},\n`,
	)
	return `${HEADER}[\n${entries.join('')}]\n`
}

async function main(args) {
	const text = readFileSync(DEFAULT_KEYS_FILE, 'utf8')
	const wanted = renderCompiledKeys(text)
	if (args.includes('--check')) {
		let have = ''
		try {
			have = readFileSync(COMPILED_KEYS_FILE, 'utf8')
		} catch {}
		if (have !== wanted)
			throw new Error(
				'src/main/kernel/keys-compiled.ts is not what kernel-keys.json gives; run node scripts/kernel/write-keys.mjs.',
			)
		return
	}
	writeFileSync(COMPILED_KEYS_FILE, wanted)
}

if (isMain(import.meta.url)) await runMain(main)
