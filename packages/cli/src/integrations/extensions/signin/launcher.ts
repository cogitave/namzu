import { chmodSync, existsSync, mkdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { atomicWrite } from '../store.js'

/**
 * Why a launcher: the sign-in entry must not name the engine's own file, because the engine moves (the
 * app keeps its engine current from the signed feed, a packaged build carries its own, a CLI install is
 * on PATH). The entry names `_runner/start.cmd` or `start.sh`, which reads where the engine is now from
 * `engine.json`. Every Namzu host rewrites that file at start when its values differ, so a kernel update
 * or a reinstall repairs the entry by running once.
 */

export interface EngineLocation {
	/** The program to start: the node binary, or the app's own binary with `ELECTRON_RUN_AS_NODE`. */
	readonly exe: string
	/** The arguments before the command words: the entry file of the engine. */
	readonly args: readonly string[]
	readonly env: Readonly<Record<string, string>>
}

export const runnerDir = (extensionsRoot: string): string => join(extensionsRoot, '_runner')

const shq = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`

/** The derived file the launcher sources on POSIX: plain assignments, no parsing at sign-in time. */
export function engineSh(e: EngineLocation): string {
	const lines = ['# Generated by Namzu from engine.json. Do not edit.']
	for (const [k, v] of Object.entries(e.env)) lines.push(`export ${k}=${shq(v)}`)
	lines.push(`NAMZU_ENGINE_EXE=${shq(e.exe)}`)
	lines.push(`set -- ${e.args.map(shq).join(' ')}`)
	return `${lines.join('\n')}\n`
}

function cmdValue(v: string): string {
	if (/["\r\n]/.test(v))
		throw new Error('a path with a quote or a line break cannot go in a launcher')
	return v.replace(/%/g, '%%')
}

/** The derived file the launcher calls on Windows. */
export function engineCmd(e: EngineLocation): string {
	const lines = ['@echo off', 'rem Generated by Namzu from engine.json. Do not edit.']
	for (const [k, v] of Object.entries(e.env)) lines.push(`set "${k}=${cmdValue(v)}"`)
	lines.push(`set "NAMZU_ENGINE_EXE=${cmdValue(e.exe)}"`)
	lines.push(`set "NAMZU_ENGINE_ARGS=${e.args.map((a) => `"${cmdValue(a)}"`).join(' ')}"`)
	return `${lines.join('\r\n')}\r\n`
}

export const START_SH = `#!/bin/sh
# Namzu extension runner launcher. Generated; Namzu rewrites it when the engine moves.
d=$(dirname "$0")
[ -f "$d/engine.sh" ] || exit 0
. "$d/engine.sh"
exec "$NAMZU_ENGINE_EXE" "$@" extension daemon start --signin
`

/**
 * On Windows the scheduled task runs this file, so the task is already the runner's parent: the last line
 * runs the runner itself (`daemon run`). `daemon start` would ask the task to run (`ensureRunner`), and
 * the task's policy ignores a second instance of itself, so nothing would ever start the runner.
 */
export const START_CMD = `@echo off\r
rem Namzu extension runner launcher. Generated; Namzu rewrites it when the engine moves.\r
set "D=%~dp0"\r
if not exist "%D%engine.cmd" exit /b 0\r
call "%D%engine.cmd"\r
"%NAMZU_ENGINE_EXE%" %NAMZU_ENGINE_ARGS% extension daemon run\r
`

/**
 * On Windows the task and the Run key start `start.vbs`, not `start.cmd`, so nothing shows on screen. A
 * `.cmd` file always gets a console window, and the task's own `Hidden` setting only hides the task from
 * the Task Scheduler list. `wscript.exe` is a program with no console: it runs `start.cmd` with window
 * style 0 (hidden) and waits for it, so the task is still the runner's parent (restart on failure and
 * the ignored second instance keep working). Chosen over `conhost.exe --headless` because that switch
 * is undocumented and needs a recent Windows 10; the script host is on every supported Windows and
 * needs no administrator rights. A computer whose policy turns the script host off cannot start the
 * runner at sign-in; the Namzu app still starts it when it opens.
 */
export const START_VBS = [
	"' Namzu extension runner, started with no window. Generated; Namzu rewrites it when the engine moves.",
	'Option Explicit',
	'Dim sh, fso, here, rc',
	'Set sh = CreateObject("WScript.Shell")',
	'Set fso = CreateObject("Scripting.FileSystemObject")',
	'here = fso.GetParentFolderName(WScript.ScriptFullName)',
	'rc = sh.Run("cmd.exe /d /c " & Chr(34) & Chr(34) & here & "\\start.cmd" & Chr(34) & Chr(34), 0, True)',
	'WScript.Quit rc',
	'',
].join('\r\n')

export interface LauncherPaths {
	readonly launcher: string
	/** Windows: the script that runs the launcher with no window; the sign-in entry names this one. */
	readonly hidden?: string
	readonly engineJson: string
}

/**
 * Write `engine.json`, its derived file and the launcher, only when something differs. Returns the
 * launcher path and whether anything was rewritten.
 */
export function writeLauncher(
	extensionsRoot: string,
	engine: EngineLocation,
	platform: NodeJS.Platform = process.platform,
): LauncherPaths & { changed: boolean } {
	const dir = runnerDir(extensionsRoot)
	mkdirSync(dir, { recursive: true, mode: 0o700 })
	const win = platform === 'win32'
	const engineJson = join(dir, 'engine.json')
	const launcher = join(dir, win ? 'start.cmd' : 'start.sh')
	const derived = join(dir, win ? 'engine.cmd' : 'engine.sh')
	const json = `${JSON.stringify({ exe: engine.exe, args: engine.args, env: engine.env }, null, 2)}\n`
	const want: [string, string, number][] = [
		[engineJson, json, 0o600],
		[derived, win ? engineCmd(engine) : engineSh(engine), 0o600],
		[launcher, win ? START_CMD : START_SH, 0o700],
	]
	const hidden = win ? join(dir, 'start.vbs') : undefined
	if (hidden) want.push([hidden, START_VBS, 0o600])
	let changed = false
	for (const [file, text, mode] of want) {
		let cur: string | undefined
		try {
			cur = existsSync(file) ? readFileSync(file, 'utf8') : undefined
		} catch {
			cur = undefined
		}
		if (cur === text) continue
		atomicWrite(file, text, mode)
		if (!win) chmodSync(file, mode)
		changed = true
	}
	return { launcher, ...(hidden ? { hidden } : {}), engineJson, changed }
}
